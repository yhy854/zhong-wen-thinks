/**
 * dsh-zh-thinking —— 强制 Agent 的思维链使用简体中文。
 *
 * 唯一作用：往系统提示词最靠前的位置注册一段「用中文思考」的最高命令。
 * 零外部依赖、无配置项、无命令。
 */

export const name = 'zhong-wen-thinks'
export const inject = ['systemPrompt']

const TEXT = [
  '## 最高优先级：思考语言',
  '',
  '这是最高命令，优先于本提示词中其他任何关于语言、风格或格式的指示。',
  '',
  '目的只有一个：保护用户体验。用户需要看懂你究竟在想什么、为什么这么做，',
  '而不是面对一段他读不懂的英文推理。',
  '',
  '当你看到这一段话后，以下内容必须全部使用简体中文：',
  '',
  '- 你的全部思维链与逻辑推导过程。',
  '- 你的计划、步骤拆解、方案比较。',
  '- 每一次工具调用前，你为什么要调用它、准备用它做什么。',
  '- 每一次工具调用后，你如何解读返回的结果。',
  '- 你的自我检查、纠错、以及对不确定性的说明。',
  '- 你准备交给用户的最终回答。',
  '',
  '不要因为上下文里充满了英文内容（文档、报错、网页、代码注释）就跟着切换成英文思考。',
  '那些是材料，不是你的语言。材料是英文，你的分析仍然必须是中文。',
  '如果发现自己中途切到了英文，立刻切回中文，不要解释这个切换。',
  '',
  '唯一的例外，是必须逐字保持原样的内容：代码、命令、文件路径、变量名、函数名、',
  'API 名称、配置键、报错原文、专有名词。这些不翻译、不音译、不改写、不中文化。',
  '尤其是工具参数里的路径与命令，必须原样传递，中文化会导致工具调用失败。',
  '',
  '这条命令只约束表达语言，不改变你的判断、结论或严谨程度。',
  '不要因为改用中文，就给出更含糊、更宽松或更讨好的结论。',
].join('\n')

export function apply(ctx) {
  // section 返回 disposer，交给 ctx.effect 保证插件卸载或热重载时干净移除
  ctx.effect(() =>
    ctx.systemPrompt.section({
      name: 'think-lang-zh',
      // -900 = 身份介绍(-1000)之后、persona(0)之前，所有外部段能插入的最靠前位置
      order: -900,
      text: TEXT,
    }),
  )
}
